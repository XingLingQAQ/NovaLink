def _repo_root() -> Path:
    current = Path(__file__).resolve().parent
    for candidate in (current, *current.parents):
        if (candidate / "settings.gradle").exists() or (candidate / ".git").exists():
            return candidate
    raise RuntimeError(f"Could not locate repository root above {current}")


GOLDEN_DIR = _repo_root() / "test" / "protocol-golden"


def _load_samples() -> list[dict]:
    manifest_path = GOLDEN_DIR / "manifest.json"
    if not manifest_path.exists():
        raise RuntimeError(
            f"Golden manifest not found: {manifest_path} "
            "(run the Java GoldenFileGenerator first)"
        )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    samples = []
    for entry in manifest["samples"]:
        descriptor = json.loads(
            (GOLDEN_DIR / f"{entry['name']}.json").read_text(encoding="utf-8")
        )
        samples.append(descriptor)
    return samples


