def _decode_frame(frame: bytes) -> tuple[int, uuid.UUID, Packet, PacketBuffer]:
    """Parse Length(VarInt) | PacketID | RequestID | Payload."""
    length, consumed = VarInt.decode(frame)
    body = frame[consumed:]
    assert length == len(body), "VarInt length prefix must equal body size"
    buffer = PacketBuffer(body)
    packet_id = buffer.read_byte()
    request_id = buffer.read_uuid()
    packet = decode_packet(packet_id, buffer)
    return packet_id, request_id, packet, buffer


def _encode_frame(packet: Packet, request_id: uuid.UUID) -> bytes:
    buffer = PacketBuffer()
    buffer.write_byte(packet.packet_id)
    buffer.write_uuid(request_id)
    packet.encode(buffer)
    body = buffer.get_bytes()
    return VarInt.encode(len(body)) + body


@pytest.mark.parametrize("descriptor", SAMPLES, ids=lambda s: s["name"])
def test_golden_sample(descriptor: dict) -> None:
    name = descriptor["name"]
    frame = (GOLDEN_DIR / f"{name}.bin").read_bytes()

    assert frame.hex() == descriptor["frameHex"], f"{name}: frameHex matches .bin"

    packet_id, request_id, packet, buffer = _decode_frame(frame)

    if isinstance(packet, UnknownPacket):
        pytest.skip(
            f"Python has no packet class for packetId 0x{descriptor['packetId']:02X} "
            f"(sample {name})"
        )

    assert packet_id == descriptor["packetId"], f"{name}: packet id"
    assert request_id == uuid.UUID(descriptor["requestId"]), f"{name}: request id"
    assert buffer.remaining() == 0, f"{name}: payload fully consumed"

    field_map = _FIELD_MAPS[type(packet)]
    for json_key, attr in field_map.items():
        expected = descriptor["fields"][json_key]
        actual = getattr(packet, attr)
        if json_key in _STR_UUID_FIELDS:
            expected = uuid.UUID(expected)
        assert actual == expected, f"{name}: field {json_key}"

    if not descriptor["reencodeExact"] or "python" in descriptor.get("knownDrift", {}):
        return  # legacy wire form or documented Python drift: decode-only.

    reencoded = _encode_frame(packet, request_id)
    assert reencoded.hex() == frame.hex(), (
        f"{name}: re-encoded frame is byte-identical to the golden frame"
    )


@pytest.mark.parametrize("descriptor", FIXED_DRIFT_SAMPLES, ids=lambda s: s["name"])
def test_fixed_drift_is_byte_exact(descriptor: dict) -> None:
    """Regression pin for the fixed Python drift.

    ChatMessage placeholders were dropped and ConfigSync normalized an empty
    config_json to "{}"; these samples must now re-encode byte-identical to
    the golden frame.
    """
    name = descriptor["name"]
    frame = (GOLDEN_DIR / f"{name}.bin").read_bytes()

    _, request_id, packet, _ = _decode_frame(frame)
    assert not isinstance(packet, UnknownPacket)

    reencoded = _encode_frame(packet, request_id)
    assert reencoded.hex() == frame.hex(), (
        f"{name}: fixed drift must stay fixed (re-encode is byte-identical)"
    )
