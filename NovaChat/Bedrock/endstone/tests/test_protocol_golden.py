"""
Cross-language golden byte verification (Python side).

The golden frames under <repo>/test/protocol-golden are generated by the
authoritative Java implementation (NovaChat/common, GoldenFileGenerator).
For every sample this suite:

1. decodes the .bin frame with the Endstone protocol classes,
2. asserts every decoded field matches the .json descriptor,
3. re-encodes and asserts byte-for-byte equality with the .bin
   (skipped for legacyWire samples and Python knownDrift samples).

Historical Python drift, now fixed (regression-pinned in
test_fixed_drift_is_byte_exact):

- ChatMessagePacket used to drop the placeholders map (decode discarded
  contents, encode always wrote varint 0); it now round-trips the map.
- ConfigSyncPacket.encode used to normalize an empty config_json string to
  "{}" ("or" treated the empty string as falsy); like Java it now only maps
  None to "{}" and preserves the empty string.
"""

